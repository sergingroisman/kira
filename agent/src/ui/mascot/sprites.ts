export function spriteFrameCount(species: Species): number {
  return BODIES[species].length;
}

export function renderSprite(species: Species, frame: number, eye: string): string[] {
  const frames = BODIES[species];
  const body = frames[frame % frames.length]!;
  return body.map((line) => line.replaceAll("{E}", eye));
}
